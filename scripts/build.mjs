import {mkdir,readFile,writeFile,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
await mkdir(resolve(root,'dist'),{recursive:true});
const settings=await readFile(resolve(root,'src/settings.js'),'utf8');
const client=await readFile(resolve(root,'src/client.js'),'utf8');
const plain = source => source.replace(/^import .*?;\s*$/gm,'').replace(/^export /gm,'');
await writeFile(resolve(root,'plugin/client.js'),`// GENERATED by scripts/build.mjs; edit src/.\nwindow.__ModuleLoader__.load({id:'dsh-open-meadow',factory:(require)=>{\n'use strict';\nconst {createElement:h}=require('react');\n${plain(settings)}\n${plain(client)}\nreturn {name,inject,apply};\n}});\n`);
for (const name of ['scene.html','scene.css','renderer.js','settings.js','ui.css']) await copyFile(resolve(root,'src',name),resolve(root,'dist',name));
await copyFile(resolve(root,'assets/production/coast.webp'),resolve(root,'dist/coast.webp'));
await copyFile(resolve(root,'assets/production/cloud.png'),resolve(root,'dist/cloud.png'));
const manifest={};
for (const file of ['plugin/index.js','plugin/client.js','dist/scene.html','dist/scene.css','dist/renderer.js','dist/settings.js','dist/ui.css','dist/coast.webp','dist/cloud.png']) {
 const body=await readFile(resolve(root,file));manifest[file]={bytes:body.length,sha256:createHash('sha256').update(body).digest('hex')};
}
await writeFile(resolve(root,'artifacts/build-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log('Built Host + ModuleLoader Client + local scene assets. No network/CDN dependencies.');
